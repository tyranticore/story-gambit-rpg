export const getPathPairKey = (id1, id2) => {
  return [id1, id2].sort().join('__');
};

export const generateSvgPathData = (fromNode, toNode, curveConfig, width = 1800, height = 500) => {
  if (!fromNode || !toNode) return '';
  
  const x1 = (fromNode.x / 100) * width;
  const y1 = (fromNode.y / 100) * height;
  const x2 = (toNode.x / 100) * width;
  const y2 = (toNode.y / 100) * height;

  if (curveConfig && curveConfig.controlPoints && curveConfig.controlPoints.length > 0) {
    const cps = curveConfig.controlPoints.map(cp => ({
      x: (cp.x / 100) * width,
      y: (cp.y / 100) * height
    }));
    const isReversed = fromNode.id > toNode.id;
    const orderedCps = isReversed ? [...cps].reverse() : cps;

    if (orderedCps.length === 1) {
      return `M ${x1} ${y1} Q ${orderedCps[0].x} ${orderedCps[0].y} ${x2} ${y2}`;
    } else if (orderedCps.length === 2) {
      return `M ${x1} ${y1} C ${orderedCps[0].x} ${orderedCps[0].y}, ${orderedCps[1].x} ${orderedCps[1].y}, ${x2} ${y2}`;
    }
  }

  // Fallback straight line
  return `M ${x1} ${y1} L ${x2} ${y2}`;
};

export const getBezierPoint = (fromNode, toNode, curveConfig, t) => {
  if (!fromNode || !toNode) return { x: 0, y: 0 };
  if (!curveConfig || !curveConfig.controlPoints || curveConfig.controlPoints.length === 0) {
    return {
      x: fromNode.x + (toNode.x - fromNode.x) * t,
      y: fromNode.y + (toNode.y - fromNode.y) * t
    };
  }

  const isReversed = fromNode.id > toNode.id;
  const orderedCps = isReversed ? [...curveConfig.controlPoints].reverse() : curveConfig.controlPoints;

  if (orderedCps.length === 1) {
    const cp = orderedCps[0];
    const u = 1 - t;
    const x = u * u * fromNode.x + 2 * u * t * cp.x + t * t * toNode.x;
    const y = u * u * fromNode.y + 2 * u * t * cp.y + t * t * toNode.y;
    return { x, y };
  } else if (orderedCps.length === 2) {
    const cp1 = orderedCps[0];
    const cp2 = orderedCps[1];
    const u = 1 - t;
    const x = u * u * u * fromNode.x + 3 * u * u * t * cp1.x + 3 * u * t * t * cp2.x + t * t * t * toNode.x;
    const y = u * u * u * fromNode.y + 3 * u * u * t * cp1.y + 3 * u * t * t * cp2.y + t * t * t * toNode.y;
    return { x, y };
  }

  return {
    x: fromNode.x + (toNode.x - fromNode.x) * t,
    y: fromNode.y + (toNode.y - fromNode.y) * t
  };
};

